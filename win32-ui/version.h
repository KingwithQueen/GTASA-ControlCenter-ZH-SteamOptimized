#ifndef GTASA_UI_VERSION_H
#define GTASA_UI_VERSION_H

#define GTASA_VERSION_MAJOR 1
#define GTASA_VERSION_MINOR 1
#define GTASA_VERSION_PATCH 0

/* The fixed VERSIONINFO fields are 16-bit. The text always uses the full version. */
#define GTASA_VERSION_WIN32_MAJOR 1

#define GTASA_STRINGIZE_IMPL(value) #value
#define GTASA_STRINGIZE(value) GTASA_STRINGIZE_IMPL(value)
#define GTASA_VERSION_TEXT GTASA_STRINGIZE(GTASA_VERSION_MAJOR) "." \
    GTASA_STRINGIZE(GTASA_VERSION_MINOR) "." GTASA_STRINGIZE(GTASA_VERSION_PATCH)
#define GTASA_VERSION_FIXED GTASA_VERSION_WIN32_MAJOR,GTASA_VERSION_MINOR,GTASA_VERSION_PATCH,0

#endif
